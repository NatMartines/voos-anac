-- Dia 1: ambiente do projeto Voos ANAC

-- Warehouse com trava de custo
CREATE WAREHOUSE WH_VOOS
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

ALTER WAREHOUSE COMPUTE_WH SET AUTO_SUSPEND = 60;

CREATE RESOURCE MONITOR RM_VOOS
  WITH CREDIT_QUOTA = 20
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 75 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE WH_VOOS SET RESOURCE_MONITOR = RM_VOOS;

-- Database e camadas
CREATE DATABASE VOOS;
CREATE SCHEMA VOOS.RAW;
CREATE SCHEMA VOOS.STAGING;
CREATE SCHEMA VOOS.MARTS;

-- Role do projeto (menor privilegio)
CREATE ROLE VOOS_DEV;
GRANT USAGE ON WAREHOUSE WH_VOOS TO ROLE VOOS_DEV;
GRANT USAGE ON DATABASE VOOS TO ROLE VOOS_DEV;
GRANT ALL ON SCHEMA VOOS.RAW TO ROLE VOOS_DEV;
GRANT ALL ON SCHEMA VOOS.STAGING TO ROLE VOOS_DEV;
GRANT ALL ON SCHEMA VOOS.MARTS TO ROLE VOOS_DEV;
GRANT ROLE VOOS_DEV TO USER NATMARTINES;
GRANT ROLE VOOS_DEV TO ROLE SYSADMIN;